export const LOCALES = { vi, en };

export function getLocale() {
  const s = readProductState();
  const l = s.locale ?? s.account?.locale ?? "vi";
  return LOCALES[l] ? l : "vi";
}

/** t("db.hello", {name}) — thay {biến} trong chuỗi. */
export const t = (key, vars) => {
  const s = LOCALES[getLocale()][key] ?? vi[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => vars[k] ?? m) : s;
};

/** Đổi ngôn ngữ: lưu trên máy và (nếu đã đăng nhập) vào tài khoản qua PATCH /me. */
export async function setLocale(locale, save) {
  if (!LOCALES[locale]) return;
  updateProductState({ locale });
  document.documentElement.lang = locale;
  if (save) await save(locale).catch(() => {});
  location.reload();
}
